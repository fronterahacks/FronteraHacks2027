/**
 * Turns the pixel-art mascot PNG into voxel data for the 3D hero.
 *
 *   node scripts/voxelize-mascot.mjs            (writes src/three/mascot/mascotVoxels.ts)
 *   node scripts/voxelize-mascot.mjs --preview  (also prints an ASCII preview)
 *
 * The PNG is the original sprite scaled up ~5.8x with blurry edges, so we:
 * 1. find the art-pixel grid (cell size + offset) that makes cells most uniform,
 * 2. sample each cell's centre, drop transparent cells,
 * 3. snap the colour to the sprite's real palette (removes anti-aliasing noise).
 * Re-run it if the mascot art ever changes.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { PNG } from 'pngjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SRC = path.join(root, 'src/assets/brand/frontera-devs-mascot.png')
const OUT = path.join(root, 'src/three/mascot/mascotVoxels.ts')

// The sprite's real colours, with a name for each (used to give body parts
// different depths/behaviour in 3D, e.g. the hat can tip).
const PALETTE = {
  outline: [5, 5, 10],
  skin: [255, 173, 114],
  skinLight: [246, 183, 122],
  orange: [242, 121, 42],
  hat: [141, 67, 18],
  hatDark: [114, 59, 24],
  hatDarkest: [71, 33, 8],
  white: [240, 235, 245],
  grey: [184, 184, 184],
  greyDark: [119, 119, 119],
}

const png = PNG.sync.read(fs.readFileSync(SRC))
const { width: W, height: H, data } = png
const at = (x, y) => {
  const i = (Math.min(H - 1, Math.max(0, y)) * W + Math.min(W - 1, Math.max(0, x))) * 4
  return [data[i], data[i + 1], data[i + 2], data[i + 3]]
}
const dist2 = (a, b) => (a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2 + (a[2] - b[2]) ** 2

// --- 1. Find the grid -------------------------------------------------------
// Score = how much pixels inside each cell differ from the cell's centre.
function score(cell, ox, oy) {
  let err = 0
  for (let cy = oy + cell / 2; cy < H; cy += cell) {
    for (let cx = ox + cell / 2; cx < W; cx += cell) {
      const c = at(Math.round(cx), Math.round(cy))
      for (const [dx, dy] of [[-0.3, -0.3], [0.3, -0.3], [-0.3, 0.3], [0.3, 0.3]]) {
        const p = at(Math.round(cx + dx * cell), Math.round(cy + dy * cell))
        err += Math.min(dist2(c, p), 30000) + Math.abs(c[3] - p[3]) * 50
      }
    }
  }
  return err / ((W / cell) * (H / cell)) // normalise per cell
}

let best = { err: Infinity }
for (let cell = 5.0; cell <= 7.0; cell += 0.02) {
  for (let ox = 0; ox < cell; ox += 0.5) {
    for (let oy = 0; oy < cell; oy += 0.5) {
      const err = score(cell, ox, oy)
      if (err < best.err) best = { err, cell, ox, oy }
    }
  }
}
const { cell, ox, oy } = best

// --- 2 + 3. Sample cells and snap colours -----------------------------------
const names = Object.keys(PALETTE)
const cols = Math.floor((W - ox) / cell)
const rows = Math.floor((H - oy) / cell)
const grid = []
for (let r = 0; r < rows; r++) {
  let line = ''
  for (let c = 0; c < cols; c++) {
    const p = at(Math.round(ox + (c + 0.5) * cell), Math.round(oy + (r + 0.5) * cell))
    if (p[3] < 128) { line += '.'; continue }
    let bestName = names[0]
    for (const n of names) if (dist2(p, PALETTE[n]) < dist2(p, PALETTE[bestName])) bestName = n
    line += String.fromCharCode(97 + names.indexOf(bestName)) // a, b, c... per palette entry
  }
  grid.push(line)
}

// Trim empty rows/columns around the sprite.
while (grid.length && /^\.+$/.test(grid[0])) grid.shift()
while (grid.length && /^\.+$/.test(grid.at(-1))) grid.pop()
const usedCols = [...grid[0]].map((_, c) => grid.some((l) => l[c] !== '.'))
const first = usedCols.indexOf(true)
const last = usedCols.lastIndexOf(true)
const trimmed = grid.map((l) => l.slice(first, last + 1))

const legend = names.map((n, i) => `  ${String.fromCharCode(97 + i)}: { name: '${n}', color: '#${PALETTE[n].map((v) => v.toString(16).padStart(2, '0')).join('')}' },`).join('\n')

const out = `// GENERATED by scripts/voxelize-mascot.mjs from src/assets/brand/frontera-devs-mascot.png
// Do not edit by hand; re-run the script instead.
// Grid: ${trimmed[0].length} x ${trimmed.length} art pixels (cell ${cell.toFixed(2)}px, offset ${ox}, ${oy}).

/** One letter per palette colour, '.' = empty. Row 0 is the top of the sprite. */
export const MASCOT_GRID: string[] = [
${trimmed.map((l) => `  '${l}',`).join('\n')}
]

export const MASCOT_PALETTE: Record<string, { name: string; color: string }> = {
${legend}
}
`
fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, out)
console.log(`grid ${trimmed[0].length}x${trimmed.length}, cell ${cell.toFixed(2)}px, offset (${ox}, ${oy}), ${trimmed.join('').replace(/\./g, '').length} voxels -> ${path.relative(root, OUT)}`)
if (process.argv.includes('--preview')) console.log(trimmed.join('\n'))
